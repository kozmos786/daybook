export function versesFor(verses) {
  return verses.list ?? DEFAULT_VERSES;
}

export function dayNumber(date) {
  const [year, month, day] = date.split('-').map(Number);
  return Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
}

export function verseOfDay(verses, date) {
  const all = versesFor(verses);
  if (!all.length) return null;
  if (verses.shuffle?.date === date) {
    const shuffled = all.find((verse) => verse.id === verses.shuffle.id);
    if (shuffled) return shuffled;
  }
  return all[((dayNumber(date) % all.length) + all.length) % all.length];
}

export function pinnedVerse(verses) {
  return versesFor(verses).find((verse) => verse.id === verses.pinned) ?? null;
}

export function shuffleVerse(workspace, date) {
  const all = versesFor(workspace.verses);
  if (all.length < 2) return workspace;
  const current = verseOfDay(workspace.verses, date);
  const others = all.filter((verse) => verse.id !== current?.id);
  const pick = others[Math.floor(Math.random() * others.length)];
  return { ...workspace, verses: { ...workspace.verses, shuffle: { date, id: pick.id } } };
}

export function togglePin(workspace, id) {
  return { ...workspace, verses: { ...workspace.verses, pinned: workspace.verses.pinned === id ? null : id } };
}

function withList(workspace, change) {
  const list = change(versesFor(workspace.verses).map((verse) => ({ ...verse })));
  return { ...workspace, verses: { ...workspace.verses, list } };
}

export function saveVerse(workspace, { id, ref, text }) {
  return withList(workspace, (list) => (id && list.some((verse) => verse.id === id)
    ? list.map((verse) => (verse.id === id ? { id, ref, text } : verse))
    : [...list, { id: crypto.randomUUID(), ref, text }]));
}

export function removeVerse(workspace, id) {
  const next = withList(workspace, (list) => list.filter((verse) => verse.id !== id));
  return { ...next, verses: { ...next.verses, pinned: next.verses.pinned === id ? null : next.verses.pinned } };
}

export function resetVerses(workspace) {
  return { ...workspace, verses: { list: null, pinned: null, shuffle: null } };
}
